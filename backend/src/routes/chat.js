import {Router} from 'express';
import {authenticateToken,requireStudent,requireSuperAdmin} from '../middlewares/auth.js';
import {asyncHandler} from '../utils/errors.js';
import {rateLimit} from '../middlewares/rate-limit.js';
import * as service from '../services/chat.js';
const router=Router(),h=fn=>asyncHandler(async(r,res)=>res.json({data:await fn(r)}));
router.use(authenticateToken);
router.get('/reports',requireSuperAdmin,h(()=>service.reports()));
router.put('/reports/:id',requireSuperAdmin,h(r=>service.moderate(r.params.id,r.body)));
router.use(requireStudent);
router.get('/students',rateLimit({max:30,keyPrefix:'chat-search'}),h(r=>service.search(r.user.id,r.query.q)));
router.get('/rooms',h(r=>service.rooms(r.user.id)));
router.post('/rooms',rateLimit({max:10,keyPrefix:'chat-create'}),h(r=>service.createRoom(r.user.id,r.body)));
router.get('/rooms/:id/messages',h(r=>service.messages(r.user.id,r.params.id,r.query.before)));
router.post('/rooms/:id/messages',rateLimit({max:30,keyPrefix:'chat-send'}),h(r=>service.send(r.user.id,r.params.id,r.body)));
router.put('/rooms/:id/read',h(r=>service.read(r.user.id,r.params.id)));
router.put('/rooms/:id/members',rateLimit({max:20,keyPrefix:'chat-members'}),h(r=>service.changeMembers(r.user.id,r.params.id,r.body)));
router.get('/blocks',h(r=>service.blocks(r.user.id)));
router.put('/blocks/:id',h(r=>service.block(r.user.id,r.params.id,true)));
router.delete('/blocks/:id',h(r=>service.block(r.user.id,r.params.id,false)));
router.post('/messages/:id/report',rateLimit({max:10,keyPrefix:'chat-report'}),h(r=>service.report(r.user.id,r.params.id,r.body)));
router.delete('/messages/:id',h(r=>service.hideOwn(r.user.id,r.params.id)));
export default router;
