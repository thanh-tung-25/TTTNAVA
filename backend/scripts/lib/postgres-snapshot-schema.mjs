import {createHash} from 'node:crypto';

export function ident(value){
  if(!/^[A-Za-z_][A-Za-z0-9_]*$/.test(value))throw Error('Unsupported identifier');
  return '"'+value+'"';
}
export const literal=value=>"'"+String(value).replaceAll("'","''")+"'";
export function utcTimestamp(value){
  let text=String(value).replace(' ','T');
  if(/[+-]\d\d$/.test(text))text+=':00';
  if(!/(?:Z|[+-]\d\d:\d\d)$/i.test(text))text+='Z';
  return new Date(text).toISOString();
}
function label(value){return value.length<=63?value:value.slice(0,50)+'_'+createHash('sha256').update(value).digest('hex').slice(0,12);}
export function enumValues(type){
  if(!/^enum\(/i.test(type))throw Error('Not an enum definition');
  const inner=type.slice(type.indexOf('(')+1,-1),values=[];let i=0;
  while(i<inner.length){
    if(inner[i]!=="'")throw Error('Unsupported enum syntax');i++;let value='',closed=false;
    while(i<inner.length){
      const c=inner[i++];
      if(c==='\\'){if(i>=inner.length)throw Error('Invalid enum escape');value+=inner[i++];}
      else if(c==="'"){if(inner[i]==="'"){value+="'";i++;}else{closed=true;break;}}
      else value+=c;
    }
    if(!closed)throw Error('Unclosed enum value');values.push(value);
    if(i<inner.length&&inner[i++]!==',')throw Error('Invalid enum separator');
  }
  return values;
}
export function isJsonColumn(manifest,column){
  return column.dataType==='json'||manifest.checks.some(c=>c.tableName===column.tableName&&c.expression.toLowerCase()===`json_valid(\`${column.name}\`)`);
}
export function pgType(manifest,column){
  if(isJsonColumn(manifest,column))return 'jsonb';
  const t=column.dataType,definition=column.columnType.toLowerCase();
  if(['varchar','char'].includes(t)){
    const match=definition.match(/^(?:var)?char\((\d+)\)$/);if(!match)throw Error('Unsupported character type');
    return t+'('+match[1]+')';
  }
  if(['tinytext','text','mediumtext','longtext','enum'].includes(t))return 'text';
  if(/blob|binary/.test(t))return 'bytea';
  if(t==='tinyint')return 'smallint';
  if(t==='smallint')return definition.includes('unsigned')?'integer':'smallint';
  if(t==='int'||t==='integer')return definition.includes('unsigned')?'bigint':'integer';
  if(t==='bigint')return 'bigint';
  if(t==='decimal'){
    const match=definition.match(/^decimal\((\d+),(\d+)\)$/);if(!match)throw Error('Unsupported decimal type');
    return `numeric(${match[1]},${match[2]})`;
  }
  if(t==='date')return 'date';
  if(t==='datetime'||t==='timestamp')return 'timestamptz'+(definition.includes('(3)')?'(3)':'(0)');
  throw Error('Unsupported MySQL type: '+t);
}
function defaultSql(column){
  const d=column.defaultValue;
  if(d===null||d==='NULL')return '';
  if(/^current_timestamp(?:\(\d*\))?$/i.test(d))return ' DEFAULT CURRENT_TIMESTAMP';
  if(/^-?\d+(?:\.\d+)?$/.test(String(d)))return ' DEFAULT '+d;
  if(/^'(?:[^']|'')*'$/.test(d))return ' DEFAULT '+d;
  throw Error('Unsupported default: '+column.tableName+'.'+column.name);
}
export function schemaPlan(manifest,schema='ttnava_stage'){
  if(!manifest.complete||!manifest.checks.every(c=>c.tableName))throw Error('Refresh the source snapshot with table-qualified checks');
  ident(schema);const before=[],after=[],security=[];
  const full=table=>ident(schema)+'.'+ident(table);
  before.push('CREATE SCHEMA '+ident(schema));
  before.push(`REVOKE ALL ON SCHEMA ${ident(schema)} FROM PUBLIC,anon,authenticated`);
  for(const table of manifest.tables){
    const columns=manifest.columns.filter(c=>c.tableName===table.name);
    const definitions=columns.map(c=>{
      const auto=c.extra.includes('auto_increment');let d=ident(c.name)+' '+pgType(manifest,c);
      if(auto)d+=' GENERATED BY DEFAULT AS IDENTITY';else d+=defaultSql(c);
      if(c.isNullable==='NO')d+=' NOT NULL';
      if(c.dataType==='enum')d+=' CHECK ('+ident(c.name)+' IN ('+enumValues(c.columnType).map(literal).join(',')+'))';
      if(['tinyint','smallint','int','bigint'].includes(c.dataType)&&c.columnType.includes('unsigned'))d+=' CHECK ('+ident(c.name)+'>=0)';
      return d;
    });
    if(table.primaryKey.length)definitions.push('PRIMARY KEY ('+table.primaryKey.map(ident).join(',')+')');
    for(const check of manifest.checks.filter(c=>c.tableName===table.name)){
      if(/^json_valid\(/i.test(check.expression))continue; // native jsonb validates JSON itself
      if(!/^[\w\s`'().,<>=!+-]+$/.test(check.expression))throw Error('Unsupported check expression');
      definitions.push('CONSTRAINT '+ident(label(check.name))+' CHECK ('+check.expression.replace(/`([A-Za-z_][A-Za-z0-9_]*)`/g,'"$1"')+')');
    }
    before.push('CREATE TABLE '+full(table.name)+' (\n  '+definitions.join(',\n  ')+'\n)');
    const indexes=new Map();
    for(const index of manifest.indexes.filter(i=>i.tableName===table.name&&i.name!=='PRIMARY')){
      if(!index.columnName)throw Error('Expression index needs manual migration');
      if(!indexes.has(index.name))indexes.set(index.name,[]);indexes.get(index.name).push(index);
    }
    for(const [name,index] of indexes)before.push('CREATE '+(Number(index[0].nonUnique)===0?'UNIQUE ':'')+'INDEX '+ident(label(table.name+'_'+name))+' ON '+full(table.name)+' ('+index.map(i=>ident(i.columnName)).join(',')+')');
    const foreign=new Map();
    for(const key of manifest.keys.filter(k=>k.tableName===table.name&&k.referencedTable)){
      if(!foreign.has(key.constraintName))foreign.set(key.constraintName,[]);foreign.get(key.constraintName).push(key);
    }
    for(const [name,keys] of foreign){
      const rule=manifest.foreignKeyRules.find(r=>r.tableName===table.name&&r.name===name);
      if(!rule||![rule.deleteRule,rule.updateRule].every(r=>['CASCADE','RESTRICT','SET NULL','NO ACTION'].includes(r)))throw Error('Unsupported foreign key rule');
      after.push('ALTER TABLE '+full(table.name)+' ADD CONSTRAINT '+ident(label(name))+' FOREIGN KEY ('+keys.map(k=>ident(k.columnName)).join(',')+') REFERENCES '+full(keys[0].referencedTable)+' ('+keys.map(k=>ident(k.referencedColumn)).join(',')+') ON DELETE '+rule.deleteRule+' ON UPDATE '+rule.updateRule);
    }
    security.push('ALTER TABLE '+full(table.name)+' ENABLE ROW LEVEL SECURITY');
    security.push('REVOKE ALL ON TABLE '+full(table.name)+' FROM PUBLIC,anon,authenticated');
  }
  return {schema,before,after,security,full};
}
