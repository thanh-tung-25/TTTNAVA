import { Router } from 'express';
import * as c from '../controllers/chinese-controller.js';
import { authenticateToken, requireAdmin, requirePlayer, requireStudent } from '../middlewares/auth.js';
import { uploadDocx } from '../middlewares/upload-docx.js';
import { rateLimit } from '../middlewares/rate-limit.js';
import { query } from '../config/db.js';
import { one } from '../repositories/chinese.js';
import { asyncHandler } from '../utils/errors.js';
import { parse } from '../validators/chinese.js';
import { z } from 'zod';
import { createSet, removeContent } from '../services/chinese-manage.js';
import { chineseCourseGuard } from '../middlewares/course-access.js';
import { sendArchive, DOCX_MIME } from '../services/private-storage.js';
import {adminActivities,saveActivities,validateActivities} from '../services/chinese-activities.js';
import {quizPlan} from '../services/chinese-quiz-plan.js';
import speakingAssessmentRouter from './chinese-speaking-assessment.js';
const router=Router();
router.use(authenticateToken,requirePlayer);
router.use(chineseCourseGuard);
router.use(speakingAssessmentRouter);
router.get('/catalog',c.catalog);
router.get('/sets/:id',c.detail);
router.get('/sets/:id/quiz-plan',requireStudent,c.handler(r=>quizPlan(r.user.id,r.params.id)));
router.get('/sets/:id/study/:itemId',requireStudent,c.studyCard);
router.get('/tests',c.tests);
router.get('/notebook',requireStudent,c.notebook);
router.put('/reviews/:id',requireStudent,c.review);
router.put('/sets/:id/progress',requireStudent,c.progress);
router.get('/history',requireStudent,c.history);
router.post('/attempts',requireStudent,rateLimit({windowMs:60000,max:20,keyPrefix:'chinese-start'}),c.start);
router.get('/attempts/:id',requireStudent,c.attempt);
router.post('/attempts/:id/answers',requireStudent,c.answer);
router.post('/attempts/:id/finish',requireStudent,c.finish);
router.use(requireAdmin);
router.get('/lessons/:id/activities',c.handler(r=>adminActivities(r.params.id)));
router.put('/lessons/:id/activities',c.handler(r=>saveActivities(r.params.id,r.body)));
router.post('/lessons/:id/activities/preview',c.handler(async r=>{await adminActivities(r.params.id);return validateActivities({...r.body,status:'published'});}));
router.get('/stats',c.stats);
router.put('/levels/:id',c.handler(async r=>{
 const id=parse(z.coerce.number().int().min(1).max(9),r.params.id);
 const d=parse(z.object({title:z.string().trim().min(1).max(100),description:z.string().max(20000).default('')}),r.body);
 await query('UPDATE chinese_levels SET title=?,description=? WHERE id=?',[d.title,d.description,id]);return {id};
}));
router.post('/lessons',c.saveLesson);
router.delete('/lessons/:id',c.handler(r=>removeContent('lesson',r.params.id)));
router.post('/sets',c.handler(r=>createSet(r.body)));
router.delete('/sets/:id',c.handler(r=>removeContent('set',r.params.id)));
router.delete('/tests/:id',c.handler(r=>removeContent('test',r.params.id)));
router.put('/lessons/:id',c.saveLesson);
router.post('/imports',rateLimit({windowMs:60000,max:10,keyPrefix:'chinese-import'}),uploadDocx,c.importWord);
router.put('/sets/:id',c.saveSet);
router.post('/sets/:id/reparse',c.reparseWord);
router.post('/tests',c.saveTest);
router.put('/tests/:id',c.saveTest);
router.get('/documents/:id',asyncHandler(async(r,res)=>{
 const doc=await one('SELECT filename,original FROM chinese_documents WHERE id=?',[r.params.id]);
 await sendArchive(res,'chinese_documents/'+r.params.id,doc.original,DOCX_MIME,doc.filename);
}));
export default router;
