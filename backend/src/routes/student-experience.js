import {Router} from 'express';
import {z} from 'zod';
import {authenticateToken,requireStudent,requireAdmin} from '../middlewares/auth.js';
import {asyncHandler} from '../utils/errors.js';
import {rateLimit} from '../middlewares/rate-limit.js';
import * as study from '../services/student-experience.js';
import * as rewards from '../services/student-rewards.js';
import * as connections from '../services/student-connections.js';
import * as assignments from '../services/study-assignments.js';
const router=Router();
const course=req=>z.string().min(1).max(32).parse(req.get('X-Course-Id')||req.cookies?.ttnava_course||req.query.courseId||'');
const handle=fn=>asyncHandler(async(req,res)=>{const data=await fn(req);res.set('Cache-Control','no-store').json({data});});
router.use(authenticateToken);
router.get('/assignments/manage/courses',requireAdmin,handle(r=>assignments.staffAssignmentCourses(r.user)));
router.get('/assignments/manage/choices',requireAdmin,handle(r=>assignments.assignmentChoices(r.user,z.string().max(32).parse(r.query.courseId))));
router.get('/assignments/manage/metrics',requireAdmin,handle(r=>assignments.studentExperienceMetrics(r.user,z.string().max(32).parse(r.query.courseId))));
router.get('/assignments/manage',requireAdmin,handle(r=>assignments.staffAssignments(r.user)));
router.post('/assignments/manage',requireAdmin,rateLimit({max:10,keyPrefix:'create-assignment'}),handle(async r=>{const data=await assignments.createAssignment(r.user,r.body);r.res.locals.adminAuditWritten=true;return data;}));
router.get('/assignments/manage/:id',requireAdmin,handle(r=>assignments.staffAssignmentDetail(r.user,r.params.id)));
router.post('/assignments/manage/:id/review/:studentId',requireAdmin,handle(async r=>{const data=await assignments.reviewAssignment(r.user,r.params.id,r.params.studentId,r.body);r.res.locals.adminAuditWritten=true;return data;}));
router.use(requireStudent);
router.get('/preferences',handle(r=>study.preferences(r.user.id)));
router.put('/preferences',handle(r=>study.savePreferences(r.user.id,r.body)));
router.get('/dashboard',handle(r=>study.experienceDashboard(r.user.id,course(r))));
router.get('/catalog',handle(r=>study.learningCatalog(r.user.id,course(r))));
router.get('/vocabulary',handle(r=>study.labVocabulary(r.user.id,course(r))));
router.put('/focus',handle(r=>study.saveFocus(r.user.id,course(r),r.body)));
router.get('/progress',handle(r=>study.experienceProgress(r.user.id,course(r))));
router.post('/runs',rateLimit({max:20,keyPrefix:'experience-run'}),handle(r=>study.startLearningRun(r.user.id,course(r),r.body)));
router.get('/runs/:id',handle(r=>study.learningRunState(r.user.id,z.uuid().parse(r.params.id))));
router.put('/runs/:id/draft',handle(r=>study.saveLearningDraft(r.user.id,z.uuid().parse(r.params.id),r.body)));
router.post('/runs/:id/answer',handle(r=>study.answerLearningRun(r.user.id,z.uuid().parse(r.params.id),r.body)));
router.post('/runs/:id/finish',handle(r=>study.finishLearningRun(r.user.id,z.uuid().parse(r.params.id))));
router.get('/runs/:id/hint',handle(r=>study.learningHint(r.user.id,z.uuid().parse(r.params.id),r.query.level)));
router.get('/rewards',handle(r=>rewards.rewardState(r.user.id,course(r))));
router.post('/rewards/sync',handle(r=>rewards.syncBadges(r.user.id,course(r))));
router.post('/rewards/claim/:key',handle(r=>rewards.claimDailyTask(r.user.id,course(r),r.params.key)));
router.post('/store/:sku/buy',handle(r=>rewards.buyCosmetic(r.user.id,r.params.sku)));
router.post('/store/:sku/equip',handle(r=>rewards.equipCosmetic(r.user.id,r.params.sku)));
router.get('/gallery',handle(r=>rewards.gallery(r.user.id,course(r))));
router.post('/gallery',handle(r=>rewards.saveGallery(r.user.id,course(r),r.body)));
router.delete('/gallery/:id',handle(r=>rewards.deleteGallery(r.user.id,r.params.id)));
router.get('/duels',handle(r=>connections.listAsyncDuels(r.user.id,course(r))));
router.post('/duels',rateLimit({max:10,keyPrefix:'async-duel'}),handle(r=>connections.createAsyncDuel(r.user.id,course(r),r.body)));
router.post('/duels/:id/respond',handle(r=>connections.respondAsyncDuel(r.user.id,r.params.id,r.body)));
router.get('/assignments',handle(r=>assignments.studentAssignments(r.user.id,course(r))));
router.get('/assignments/:id',handle(r=>assignments.studentAssignment(r.user.id,r.params.id)));
router.post('/assignments/:id/start',handle(r=>assignments.startAssignment(r.user.id,r.params.id)));
router.put('/assignments/:id/writing',handle(r=>assignments.submitWriting(r.user.id,r.params.id,r.body)));
router.post('/guardian/code',rateLimit({windowMs:3600000,max:5,keyPrefix:'guardian-code'}),handle(r=>connections.createGuardianCode(r.user.id)));
router.get('/guardian/links',handle(r=>connections.guardianConnections(r.user.id)));
router.post('/guardian/links',rateLimit({windowMs:3600000,max:10,keyPrefix:'guardian-link'}),handle(r=>connections.requestGuardianLink(r.user.id,r.body)));
router.post('/guardian/links/:id',handle(r=>connections.respondGuardianLink(r.user.id,r.params.id,r.body)));
router.get('/guardian/children/:id/courses',handle(r=>connections.childCourses(r.user.id,r.params.id)));
router.get('/guardian/children/:id/report',handle(r=>connections.guardianReport(r.user.id,r.params.id,z.string().min(1).max(32).parse(r.query.courseId))));
export default router;
