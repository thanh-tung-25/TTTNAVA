-- Apply manually to the application schema only when deployment is authorized.
-- Existing admin accounts keep full access; role remains 'admin'.
BEGIN;
SET LOCAL search_path TO ttnava_stage,pg_catalog;
ALTER TABLE profiles ADD COLUMN IF NOT EXISTS admin_scope varchar(16) NOT NULL DEFAULT 'super';
ALTER TABLE profiles ADD COLUMN IF NOT EXISTS admin_auth_version integer NOT NULL DEFAULT 0;
ALTER TABLE profiles ADD CONSTRAINT chk_profiles_admin_scope CHECK(admin_scope IN ('super','chinese','primary'));
CREATE TABLE admin_audit_log (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  actor_id char(36) REFERENCES profiles(id) ON DELETE SET NULL,
  actor_username varchar(20) NOT NULL,
  action varchar(200) NOT NULL,
  resource_type varchar(100) NOT NULL,
  resource_id varchar(100),
  details_json jsonb NOT NULL,
  created_at timestamptz(3) NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX idx_admin_audit_created ON admin_audit_log(created_at);
CREATE INDEX idx_admin_audit_actor ON admin_audit_log(actor_id,created_at);
ALTER TABLE admin_audit_log ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON TABLE admin_audit_log FROM PUBLIC,anon,authenticated;
COMMIT;
