import {writeFile} from 'node:fs/promises';
import {q1QuizVocabulary} from '../src/data/chinese-q1-quiz-vocabulary.js';
import {curriculumActivities,curriculumChatSettings,validateCurriculumChinese} from '../src/services/chinese-curriculum.js';
const aliases=[['你好','Xin Chào'],['你叫什么名字','Hỏi tên, Hỏi họ, Quốc tịch'],['很高兴认识你'],['你去哪儿'],['你要吃什么'],['你在哪儿工作'],['中国银行在哪儿'],['你的生日是几月几号'],['你喜欢中国电影还是美国电影'],['你家有几口人']];
const templates=q1QuizVocabulary.map(({number})=>{
 const activities=curriculumActivities(number),chat=curriculumChatSettings(number);
 validateCurriculumChinese([activities,chat],number);
 return {number,aliases:aliases[number-1],activities,chat};
});
await writeFile(new URL('../../frontend/assets/js/chinese-curriculum-templates.js',import.meta.url),'// Generated by backend/scripts/generate-chinese-curriculum-templates.mjs.\n// Self-practice templates only; no quiz bank or speaking assessment references.\nexport const curriculumTemplates='+JSON.stringify(templates,null,1)+';\n');
console.log('Generated templates for 10 lessons.');
